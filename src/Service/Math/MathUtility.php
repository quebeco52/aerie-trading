<?php

namespace App\Service\Math;

use App\Service\Macro\MacroEngine;

/**
 * The simulation's random source: uniform, normal, Student-t, exponential, Poisson and Pareto draws on the global or a
 * private stream, draw logging and replay, and the steps that make their own draws (jump diffusion, QE variance, SVJJ
 * and Kou jumps, two-factor OU and Schwartz, lognormal synergy). A step handed its draws is deterministic and lives in
 * StochasticProcesses. Tests subclass or mock this class to script draws.
 */
class MathUtility
{
    private static ?self $instance = null;

    public static function getInstance(): self
    {
        return self::$instance ??= new self();
    }

    /**
     * @var float|null Stores the second random number generated by the Box-Muller transform.
     */
    private ?float $spareNormal = null;

    // --- Draw Replay ---
    /** Uniform a replay hands out once its recording runs out: the median, so a branch the recording never reached draws nothing extreme. */
    public const REPLAY_EXHAUSTED_DRAW = 0.5;

    private float $randMaxInverse;
    private float $twoPi;

    /** @var list<float>|null Uniforms drawn since beginDrawLog(); null when nothing is recording. */
    private ?array $drawLog = null;

    /** The cached Box-Muller normal when the recording began, which a replay has to start from. */
    private ?float $drawLogSpare = null;

    /** @var list<float>|null The recorded uniforms a replaying instance hands out in place of fresh draws. */
    private ?array $replayDraws = null;

    private int $replayCursor = 0;

    /** A generator of this instance's own, in place of the global one; null draws from the global mt_rand stream. */
    private ?\Random\Randomizer $privateGenerator = null;

    /**
     * Constructor for MathUtility.
     * Pre-calculates constants for random number generation.
     */
    public function __construct()
    {
        $this->randMaxInverse = 1.0 / mt_getrandmax();
        $this->twoPi = 2.0 * M_PI;
    }

    /**
     * Generates a random float between 0 and 1 from a uniform distribution.
     *
     * @return float A random float in the interval [0, 1].
     */
    public function generateUniform(): float
    {
        if ($this->replayDraws !== null) {
            return $this->replayDraws[$this->replayCursor++] ?? self::REPLAY_EXHAUSTED_DRAW;
        }

        $draw = ($this->privateGenerator !== null ? $this->privateGenerator->getInt(0, mt_getrandmax()) : mt_rand()) * $this->randMaxInverse;
        if ($this->drawLog !== null) {
            $this->drawLog[] = $draw;
        }

        return $draw;
    }

    /** Starts recording every uniform this instance draws, so a calculation can later be re-run on the same draws. */
    public function beginDrawLog(): void
    {
        $this->drawLog = [];
        $this->drawLogSpare = $this->spareNormal;
    }

    /**
     * Stops recording and hands back what was drawn.
     *
     * @return array{uniforms: list<float>, spare: ?float}
     */
    public function endDrawLog(): array
    {
        $log = ['uniforms' => $this->drawLog ?? [], 'spare' => $this->drawLogSpare];
        $this->drawLog = null;

        return $log;
    }

    /**
     * An instance that hands out a recorded sequence of draws instead of fresh ones, for re-running a calculation on
     * the draws it was first run with. It never touches the global generator, so a re-run leaves the simulation's
     * own random path exactly where it was.
     *
     * @param array{uniforms?: list<float>, spare?: ?float} $log From endDrawLog(); an empty log replays nothing.
     */
    public static function replaying(array $log): self
    {
        $replay = new self();
        $replay->replayDraws = $log['uniforms'] ?? [];
        $replay->spareNormal = $log['spare'] ?? null;

        return $replay;
    }

    /**
     * An instance with a Mersenne Twister of its own, so what it draws neither takes from nor shifts the simulation's
     * global stream: a subsystem drawing here can be added to or left out of a seeded run without moving any other draw.
     *
     * @param int|null $seed Seed for a reproducible stream; null seeds it from the system's entropy.
     */
    public static function ownStream(?int $seed = null): self
    {
        $stream = new self();
        $stream->privateGenerator = new \Random\Randomizer(new \Random\Engine\Mt19937($seed));

        return $stream;
    }

    /**
     * Generates a random float between $min and $max from a uniform distribution.
     */
    public function generateUniformBetween(float $min, float $max): float
    {
        return $min + $this->generateUniform() * ($max - $min);
    }

    /**
     * Checks if an event occurs given a specific probability [0, 1].
     *
     * @param float $probability The probability of the event occurring.
     * @return bool True if the event occurred, false otherwise.
     */
    public function checkProbability(float $probability): bool
    {
        return $this->generateUniform() < $probability;
    }

    /**
     * Generates a random number from a standard normal distribution (Gaussian).
     *
     * This method uses the Box-Muller transform to convert uniformly distributed
     * random numbers (from mt_rand) into normally distributed numbers with
     * a mean of 0 and a standard deviation of 1.
     *
     * Since Box-Muller generates two numbers at once, one is returned immediately
     * and the other is stored in $spareNormal for the next call.
     *
     * @return float A random number following a standard normal distribution.
     */
    public function generateStandardNormal(): float
    {
        if ($this->spareNormal !== null) {
            $result = $this->spareNormal;
            $this->spareNormal = null;
            return $result;
        }

        do {
            $x = $this->generateUniform();
            $y = $this->generateUniform();
        } while ($x <= 0);

        $radius = sqrt(-2 * log($x));
        $angle = $this->twoPi * $y;

        $this->spareNormal = $radius * sin($angle);
        return $radius * cos($angle);
    }

    /**
     * Generates an AR(1) persistent Z-score for autoregressive dynamics.
     * Preserves unit variance (σ = 1.0) of the underlying stationary distribution.
     *
     * @param float $previousZ The previous quarter's realized Z-score (z_{t-1}).
     * @param float $phi       The autoregressive persistence coefficient (0 = i.i.d., 1 = random walk).
     * @param float|null $commonInnovation Optional firm-wide N(0,1) innovation shared by every stream this period.
     * @param float $commonLoading  One-factor loading rho in [0, 1] on the common innovation (0 = independent).
     * @return float The new Z-score z_t.
     */
    public function generatePersistentZ(float $previousZ, float $phi, ?float $commonInnovation = null, float $commonLoading = 0.0): float
    {
        $idiosyncratic = $this->generateStandardNormal();
        $innovation = $idiosyncratic;

        if ($commonInnovation !== null && $commonLoading > 0.0) {
            // One-factor model (Sharpe 1963 single-index form): e_t = rho * F_t + sqrt(1 - rho^2) * u_t
            // keeps the innovation at unit variance while two streams with loadings rho_i, rho_j
            // share innovation correlation rho_i * rho_j.
            $loading = min(1.0, $commonLoading);
            $innovation = ($loading * $commonInnovation) + (sqrt(max(0.0, 1.0 - ($loading * $loading))) * $idiosyncratic);
        }

        return ($phi * $previousZ) + (StochasticProcesses::persistentInnovationScale($phi) * $innovation);
    }

    /**
     * Calculates a log-normal random draw, used for right-skewed distributions like M&A synergy.
     *
     * @param float $mu The mean of the underlying normal distribution.
     * @param float $sigma The standard deviation of the underlying normal distribution.
     * @return float A log-normal distributed value.
     */
    public function calculateLogNormalSynergy(float $mu, float $sigma): float
    {
        return exp($mu + $sigma * $this->generateStandardNormal());
    }

    /**
     * Generates a random draw from a standardized Student's t-distribution with unit variance.
     *
     * @param int $df Degrees of freedom (must be > 2 for defined variance).
     * @return float A standardized t-distributed random variable.
     */
    public function generateStudentsT(int $df = 4): float
    {
        $df = max(3, $df);
        $chiSquare = 0.0;
        for ($i = 0; $i < $df; $i++) {
            $z = $this->generateStandardNormal();
            $chiSquare += $z * $z;
        }

        // Guard the chi-square denominator. A draw of exactly zero has probability zero in continuous theory,
        // but is reachable in practice whenever the underlying normal generator is stubbed or seeded to a
        // constant, and the resulting division by zero would abort the whole simulation tick.
        $chiSquare = max($chiSquare, 1e-12);

        $rawT = $this->generateStandardNormal() / sqrt($chiSquare / $df);
        return $rawT * sqrt(($df - 2) / $df);
    }

    /**
     * Simulates the Merton Jump Diffusion process for sudden market shocks.
     * Returns the price multiplier and the raw components of the jump.
     *
     * @param float $lambda   The jump intensity (average number of jumps per year).
     * @param float $jumpMean The mean size of a jump (log-return).
     * @param float $jumpVol  The volatility of the jump size.
     * @param float $dt       The time step in years.
     * @return array{multiplier: float, shock_pct: float|null, exponent: float|null}
     */
    public function calculateJumpDiffusion(
        float $lambda,
        float $jumpMean,
        float $jumpVol,
        float $dt
    ): array {
        $jumpProb = $lambda * $dt;

        // Roll the dice to see if a jump occurs this tick
        if ($this->checkProbability($jumpProb)) {
            $jumpZ = $this->generateStandardNormal();

            $jumpExponent = $jumpMean + ($jumpVol * $jumpZ);
            $jumpMultiplier = exp($jumpExponent);
            $shockPct = ($jumpMultiplier - 1.0) * 100.0;

            return [
                'multiplier' => $jumpMultiplier,
                'shock_pct'  => $shockPct,
                'exponent'   => $jumpExponent
            ];
        }

        // No jump occurred
        return [
            'multiplier' => 1.0,
            'shock_pct'  => null,
            'exponent'   => null
        ];
    }

    /**
     * Generates a random number from an Exponential distribution.
     *
     * @param float $rate The rate parameter (lambda) of the distribution.
     * @return float A random number drawn from the exponential distribution.
     */
    public function generateExponential(float $rate = 1.0): float
    {
        // Prevent log(0)
        $u = max($this->generateUniform(), 0.0000001);
        return -log($u) / $rate;
    }

    /**
     * Number of Poisson arrivals over an interval with the given mean (Knuth's product-of-uniforms method,
     * exact for the small means a tick produces). Unlike the Bernoulli gate the jump helpers use, more than
     * one event can land in a tick.
     */
    public function generatePoissonCount(float $mean): int
    {
        if ($mean <= 0.0) {
            return 0;
        }

        $limit = exp(-$mean);
        $count = 0;
        $product = 1.0;
        do {
            $count++;
            $product *= $this->generateUniform();
        } while ($product > $limit);

        return $count - 1;
    }

    /**
     * A single-parameter Pareto severity (Klugman, Panjer & Willmot, Loss Models): inverse-CDF draw
     * scale x U^(-1/alpha), truncated at a cap so a finite portfolio has a finite worst case. With alpha
     * between one and two the mean exists (scale x alpha / (alpha - 1)) but the untruncated variance does not,
     * which is what an insured-catastrophe tail looks like.
     */
    public function generateParetoSeverity(float $scale, float $alpha, float $cap): float
    {
        $u = max(0.0000001, 1.0 - $this->generateUniform());

        return min($cap, max(0.0, $scale) * ($u ** (-1.0 / max(0.01, $alpha))));
    }

    /**
     * Andersen's Quadratic-Exponential (QE) Discretization Scheme (2008).
     * Calculates the next variance state strictly positively, without bias.
     *
     * @param float $currentVar Current variance (Volatility squared).
     * @param float $theta      Long-term mean variance.
     * @param float $kappa      Reversion speed.
     * @param float $sigma      Volatility of volatility.
     * @param float $dt         Time step.
     * @param float|null $varianceShock Unit-variance shock to drive the step with, for a variance correlated with the
     *                          price (Heston rho); null draws a fresh one. Both branches are monotone in one uniform
     *                          U_V (Andersen 2008), so the exponential branch reads U_V = Phi(shock).
     * @return float The next strictly positive variance.
     */
    public function calculateQEVarianceStep(
        float $currentVar,
        float $theta,
        float $kappa,
        float $sigma,
        float $dt,
        ?float $varianceShock = null
    ): float {
        $expKappaDt = exp(-$kappa * $dt);

        // Calculate mean (m) and variance (s^2) of the next variance state
        $m = $theta + ($currentVar - $theta) * $expKappaDt;
        $s2 = ($currentVar * $sigma * $sigma * $expKappaDt / $kappa) * (1 - $expKappaDt)
            + ($theta * $sigma * $sigma / (2 * $kappa)) * pow(1 - $expKappaDt, 2);

        // Psi determines whether to use Quadratic or Exponential approximation
        // Clamped to a minimum of 1e-8 to prevent DivisionByZeroError if variance drops to absolute zero
        $psi = $m > 0 ? max($s2 / ($m * $m), 1e-8) : 2.0;

        $nextVar = 0.0;

        if ($psi <= 1.5) {
            // Non-central chi-square approximation (Quadratic)
            $b2 = 2 / $psi - 1 + sqrt((2 / $psi) * (2 / $psi - 1));
            $a = $m / (1 + $b2);
            $Zv = $varianceShock ?? $this->generateStandardNormal();
            $nextVar = $a * pow(sqrt($b2) + $Zv, 2);
        } else {
            // Exponential approximation
            $p = ($psi - 1) / ($psi + 1);
            $beta = (1 - $p) / $m;
            $U = $varianceShock !== null ? Distributions::calculateNormalCDF($varianceShock) : $this->generateUniform();

            if ($U > $p) {
                // Prevent log(0) if U is extremely close to 1
                $U = min($U, 0.9999999);
                $nextVar = (1 / $beta) * log((1 - $p) / (1 - $U));
            } else {
                $nextVar = 0.0;
            }
        }

        // Failsafe floor
        return max($nextVar, 0.0000001);
    }

    /**
     * SVJJ Model: Correlated Price and Variance Jumps using Kou Double-Exponential.
     *
     * @param float $lambda   Jump intensity (arrivals per year).
     * @param float $pUp      Probability that a jump is upwards (e.g., 0.3 for heavy left-tail).
     * @param float $etaUp    Rate of up-jump exponential decay.
     * @param float $etaDown  Rate of down-jump exponential decay.
     * @param float $muV      Mean of the variance jump (exponentially distributed).
     * @param float $dt       Time step.
     * @return array{price_multiplier: float, var_jump: float, shock_pct: float|null}
     */
    public function calculateSVJJJumps(
        float $lambda,
        float $pUp,
        float $etaUp,
        float $etaDown,
        float $muV,
        float $dt
    ): array {
        $jumpProb = $lambda * $dt;

        if ($this->checkProbability($jumpProb)) {
            // Price Jump (Kou Double-Exponential)
            $isUpJump = $this->generateUniform() < $pUp;

            if ($isUpJump) {
                $jumpSize = $this->generateExponential($etaUp);
                // Failsafe: Cap individual upside jumps at MAX_JUMP_LOG_RETURN (+30%, log(1.30) ≈ 0.2624)
                $jumpSize = min($jumpSize, FinancialConstants::MAX_JUMP_LOG_RETURN);
            } else {
                $jumpSize = -$this->generateExponential($etaDown);
                // Failsafe: Cap individual downside crashes at MIN_JUMP_LOG_RETURN (-30%, log(0.70) ≈ -0.3567)
                $jumpSize = max($jumpSize, FinancialConstants::MIN_JUMP_LOG_RETURN);
            }

            $priceMultiplier = exp($jumpSize);
            $shockPct = ($priceMultiplier - 1.0) * 100.0;

            // Contemporaneous variance jump (crashes spike volatility more than rallies).
            $varJump = 0.0;
            if ($muV > 0.0) {
                $meanVarJump = $isUpJump ? ($muV * StochasticProcesses::VARIANCE_JUMP_UPSIDE_MEAN_SHARE) : $muV;
                $varJump = min(
                    $this->generateExponential(1.0 / $meanVarJump),
                    $meanVarJump * StochasticProcesses::MAX_VARIANCE_JUMP_MEAN_MULTIPLE
                );
            }

            return [
                'price_multiplier' => $priceMultiplier,
                'var_jump'         => $varJump,
                'shock_pct'        => $shockPct
            ];
        }

        return [
            'price_multiplier' => 1.0,
            'var_jump'         => 0.0,
            'shock_pct'        => null
        ];
    }

    /**
     * One additive, mean-compensated Kou (2002) double-exponential jump drawn over a step of dt.
     *
     * Kou's jump is asymmetric by construction: up with probability pUp and size Exp(etaUp), otherwise down
     * with size Exp(etaDown). A low pUp with etaDown below etaUp is the rare-disaster shape Barro (2006) and
     * Gourio (2012) put on aggregate demand — long stretches of nothing, then a drop large enough that a
     * policy rule reacting to a trailing average cannot answer it within its own transmission lag. Unlike
     * calculateSVJJJumps this returns an additive increment rather than a price multiplier, so it composes
     * with a process carried in level or rate units instead of log-returns.
     *
     * The expected jump per unit time is subtracted, so adding this to a mean-reverting process moves its
     * skewness and kurtosis without moving its mean. The compensator uses the mean of the CAPPED
     * exponential, E[min(X, cap)] = (1 - e^(-eta*cap)) / eta, because the cap is part of the draw: an
     * uncapped compensator over-corrects the truncated down branch and leaves a standing positive drift.
     *
     * @param float $lambda  Jump arrivals per year.
     * @param float $pUp     Probability that a jump is upwards.
     * @param float $etaUp   Exponential rate of the up jump (mean size 1/etaUp).
     * @param float $etaDown Exponential rate of the down jump (mean size 1/etaDown).
     * @param float $cap     Absolute cap on a single jump, in the units of the process.
     * @param float $dt      Time step in years.
     * @return float The compensated jump increment, zero-mean in expectation over dt.
     */
    public function calculateCompensatedKouJump(
        float $lambda,
        float $pUp,
        float $etaUp,
        float $etaDown,
        float $cap,
        float $dt
    ): float {
        if ($lambda <= 0.0 || $etaUp <= 0.0 || $etaDown <= 0.0 || $cap <= 0.0 || $dt <= 0.0) {
            return 0.0;
        }

        $compensator = StochasticProcesses::calculateKouCompensator($lambda, $pUp, $etaUp, $etaDown, $cap, $dt);

        $jump = 0.0;
        if ($this->checkProbability($lambda * $dt)) {
            $jump = $this->generateUniform() < $pUp
                ? min($this->generateExponential($etaUp), $cap)
                : -min($this->generateExponential($etaDown), $cap);
        }

        return $jump - $compensator;
    }

    /**
     * Schwartz-Smith 2-Factor Model (2000) for industrial commodity pricing.
     * Decomposes log-price into a mean-reverting short-term deviation (chi)
     * and a drifting long-term equilibrium (xi).
     *
     * @param float $chi     Current short-term log-deviation state.
     * @param float $xi      Current long-term log-equilibrium state.
     * @param float $kappa   Mean-reversion speed of short-term deviation.
     * @param float $muXi    Drift rate of long-term equilibrium (supercycle trend).
     * @param float $sigChi  Volatility of short-term deviation.
     * @param float $sigXi   Volatility of long-term equilibrium.
     * @param float $rho     Correlation between chi and xi innovations.
     * @param float $dt      Time step in years.
     * @param float|null $dW1 Optional standard normal draw for short-term factor.
     * @param float|null $dW2 Optional standard normal draw for long-term factor uncorrected component.
     * @return array{chi: float, xi: float, spot: float}
     */
    public function calculateSchwartz2Factor(
        float $chi,
        float $xi,
        float $kappa,
        float $muXi,
        float $sigChi,
        float $sigXi,
        float $rho,
        float $dt,
        ?float $dW1 = null,
        ?float $dW2 = null
    ): array {
        $dW1 ??= $this->generateStandardNormal();
        $dW2 ??= $this->generateStandardNormal();

        $clampedRho = max(-0.99, min(0.99, $rho));
        $safeKappa = max(0.0001, $kappa);

        // Correlated standard normal innovations
        $zChi = $dW1;
        $zXi = ($clampedRho * $dW1) + (sqrt(1.0 - ($clampedRho * $clampedRho)) * $dW2);

        // Exact discretization of OU process for chi (mean-reverting to 0)
        $expKappaDt = exp(-$safeKappa * $dt);
        $chiDrift = $chi * $expKappaDt;
        $chiVariance = ($sigChi * $sigChi / (2.0 * $safeKappa)) * (1.0 - exp(-2.0 * $safeKappa * $dt));
        $nextChi = $chiDrift + sqrt($chiVariance) * $zChi;

        // Long-term equilibrium drift (Arithmetic Brownian Motion for log-equilibrium)
        $nextXi = $xi + ($muXi * $dt) + ($sigXi * sqrt($dt) * $zXi);

        $spot = exp($nextChi + $nextXi);

        return [
            'chi'  => $nextChi,
            'xi'   => $nextXi,
            'spot' => $spot,
        ];
    }

    /**
     * Two-Factor Correlated Ornstein-Uhlenbeck (OU) Process.
     * Models a spot price derived from two distinct mean-reverting log-state variables.
     * Ideal for bounded index simulations (e.g., short-term shocks vs long-term structural cycles).
     *
     * @param float $chi       Current state of Factor 1 (e.g., short-term).
     * @param float $xi        Current state of Factor 2 (e.g., long-term).
     * @param float $kappaChi  Mean-reversion speed of Factor 1.
     * @param float $kappaXi   Mean-reversion speed of Factor 2.
     * @param float $thetaChi  Equilibrium target of Factor 1.
     * @param float $thetaXi   Equilibrium target of Factor 2.
     * @param float $sigChi    Volatility of Factor 1.
     * @param float $sigXi     Volatility of Factor 2.
     * @param float $rho       Correlation coefficient between the two factors [-1, 1].
     * @param float $dt        Time step in years.
     * @param float|null $dW1  Optional standard normal draw for Factor 1.
     * @param float|null $dW2  Optional standard normal draw for Factor 2.
     * @return array{chi: float, xi: float, spot: float}
     */
    public function calculateTwoFactorOU(
        float $chi,
        float $xi,
        float $kappaChi,
        float $kappaXi,
        float $thetaChi,
        float $thetaXi,
        float $sigChi,
        float $sigXi,
        float $rho,
        float $dt,
        ?float $dW1 = null,
        ?float $dW2 = null
    ): array {
        $dW1 ??= $this->generateStandardNormal();
        $dW2 ??= $this->generateStandardNormal();

        $clampedRho = max(-0.99, min(0.99, $rho));
        $safeKappaChi = max(0.0001, $kappaChi);
        $safeKappaXi = max(0.0001, $kappaXi);

        // Correlated standard normal innovations
        $zChi = $dW1;
        $zXi = ($clampedRho * $dW1) + (sqrt(1.0 - ($clampedRho * $clampedRho)) * $dW2);

        // Exact discretization for Factor 1 (Chi)
        $expKappaChiDt = exp(-$safeKappaChi * $dt);
        $chiDrift = ($chi * $expKappaChiDt) + ($thetaChi * (1.0 - $expKappaChiDt));
        $chiVariance = ($sigChi * $sigChi / (2.0 * $safeKappaChi)) * (1.0 - exp(-2.0 * $safeKappaChi * $dt));
        $nextChi = $chiDrift + sqrt($chiVariance) * $zChi;

        // Exact discretization for Factor 2 (Xi)
        $expKappaXiDt = exp(-$safeKappaXi * $dt);
        $xiDrift = ($xi * $expKappaXiDt) + ($thetaXi * (1.0 - $expKappaXiDt));
        $xiVariance = ($sigXi * $sigXi / (2.0 * $safeKappaXi)) * (1.0 - exp(-2.0 * $safeKappaXi * $dt));
        $nextXi = $xiDrift + sqrt($xiVariance) * $zXi;

        $spot = exp($nextChi + $nextXi);

        return [
            'chi'  => $nextChi,
            'xi'   => $nextXi,
            'spot' => $spot,
        ];
    }
}
