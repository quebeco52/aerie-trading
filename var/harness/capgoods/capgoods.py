"""Capital-goods price drift by industry against the GDP deflator, from the BEA Fixed Assets accounts.

Implicit price of an industry's net stock = current-cost net stock (Table 3.1ESI) / chain-type quantity index
(Table 3.2ESI), year-end; drift = ln(P2019 / P2009) / 10 less the GDP deflator's Q4/Q4 drift over the same decade
(FRED GDPDEF). Groups of lines are aggregated as current cost over chained real stock (quantity x 2017 current cost).

Usage: python3 capgoods.py [--php OUT.php]   (downloads Section3All_xls.xlsx and GDPDEF on first run)
"""
import csv, io, json, math, os, sys, urllib.request
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.dirname(HERE))
import io_data  # sheet_grid

BEA = os.path.join(HERE, 'Section3All_xls.xlsx')
DEF = os.path.join(HERE, 'GDPDEF.csv')
if not os.path.exists(BEA):
    open(BEA, 'wb').write(urllib.request.urlopen('https://apps.bea.gov/national/FixedAssets/Release/XLS/Section3All_xls.xlsx', timeout=180).read())
if not os.path.exists(DEF):
    open(DEF, 'wb').write(urllib.request.urlopen('https://fred.stlouisfed.org/graph/fredgraph.csv?id=GDPDEF', timeout=60).read())

b = open(BEA, 'rb').read()
def table(sheet):
    g = io_data.sheet_grid(b, sheet_name=sheet)
    hdr = next(r for r in g if r.get(1) == 'Line')
    years = {c: int(v) for c, v in hdr.items() if c >= 4}
    out, names = {}, {}
    for r in g:
        if str(r.get(1, '')).isdigit():
            line = int(r[1])
            names[line] = r.get(2, '').strip()
            out[line] = {years[c]: float(v) for c, v in r.items() if c in years and v not in ('', '...', '(D)')}
    return out, names
cc, names = table('FAAt301ESI-A')
qty, _ = table('FAAt302ESI-A')

q4 = {}
for row in csv.DictReader(open(DEF)):
    if row['observation_date'].endswith('-10-01'):
        q4[int(row['observation_date'][:4])] = float(row['GDPDEF'])
DEFLATOR_DRIFT = math.log(q4[2019] / q4[2009]) / 10

def price(lines, year):
    nominal = sum(cc[l][year] for l in lines)
    real = sum(qty[l][year] / 100.0 * cc[l][2017] for l in lines)
    return nominal / real
def drift(lines):
    return math.log(price(lines, 2019) / price(lines, 2009)) / 10 - DEFLATOR_DRIFT

# Every industry but real estate, whose stock is mostly owner-occupied and rented housing: the plant of a firm with no
# sector physics.
TOP = [2, 5, 9, 13, 14, 40, 43, 48, 57, 62, 75, 76, 80, 81, 84, 85, 90, 93, 96]
MAP = {
    'AdvertisingAgencyBusinessModel': [79], 'ApparelManufacturingBusinessModel': [34], 'AutoManufacturerBusinessModel': [23],
    'BiotechBusinessModel': [38], 'ChemicalBusinessModel': [38], 'CommunicationEquipmentBusinessModel': [21],
    'ComputerHardwareBusinessModel': [21], 'ConglomerateBusinessModel': [15], 'ConstructionBusinessModel': [13],
    'ConsumerStaplesBusinessModel': [30], 'DefenseContractorBusinessModel': [24], 'EducationBusinessModel': [84],
    'FinancialDataBusinessModel': [61], 'HeavyManufacturingBusinessModel': [20], 'HomebuilderBusinessModel': [13],
    'InternetRetailBusinessModel': [47], 'LawFirmBusinessModel': [77], 'LogisticsBusinessModel': [52, 55, 56],
    'LuxuryBusinessModel': [28], 'MedicalCareFacilityBusinessModel': [85], 'MerchantHouseBusinessModel': [40],
    'MiningBusinessModel': [7], 'OilGasProducerBusinessModel': [6], 'RailroadBusinessModel': [50], 'RefiningBusinessModel': [37],
    'ReitBusinessModel': [74], 'ResortsCasinosBusinessModel': [92, 94], 'RestaurantBusinessModel': [95],
    'SecurityProtectionBusinessModel': [82], 'SemiconductorBusinessModel': [21], 'ShippingBusinessModel': [51],
    'SpecialtyIndustrialMachineryBusinessModel': [20], 'SteelManufacturingBusinessModel': [18], 'TechBusinessModel': [61],
    'TelecomBusinessModel': [60], 'ToolsAndAccessoriesBusinessModel': [19, 41], 'UtilityBusinessModel': [9],
    'WasteManagementBusinessModel': [83],
}
default = drift(TOP)
rows = {m: (drift(l), l) for m, l in MAP.items()}
print(f'GDP deflator Q4/Q4 2009-2019: {DEFLATOR_DRIFT:.4f}; all industries but real estate {default:+.4f}')
for m, (d, l) in sorted(rows.items(), key=lambda kv: kv[1][0]):
    print(f'{m:45s} {d:+.4f}  {", ".join(names[x] for x in l)}')

if '--php' in sys.argv:
    out = sys.argv[sys.argv.index('--php') + 1]
    lines = ['<?php', '', 'declare(strict_types=1);', '', 'namespace App\\Data\\Macro;', '', '/**',
             ' * Capital-goods price drift by industry, against the GDP deflator. Generated by var/harness/capgoods/capgoods.py;',
             ' * regenerate, do not edit.', ' *',
             ' * Implicit price of each industry\'s net stock of private fixed assets (BEA Fixed Assets Table 3.1ESI current cost over',
             ' * Table 3.2ESI chain-type quantity, year-end), annual log drift 2009-2019, less the GDP deflator\'s Q4/Q4 drift over',
             f' * the same decade ({DEFLATOR_DRIFT:.4f}). A negative drift is a capital good getting cheaper against what it produces.',
             ' * Keyed by business model; a model not listed takes its nearest listed parent, then the all-industry figure.',
             ' */', 'final class CapitalGoodsPrices', '{',
             '    /** Every industry but real estate (mostly housing): the plant of a firm with no sector physics. */',
             f'    public const ALL_INDUSTRIES_DRIFT = {default:.4f};', '',
             '    /** Annual drift by business model, with the BEA industries it is measured on. */',
             '    public const DRIFT_BY_MODEL = [']
    for m, (d, l) in sorted(rows.items()):
        lines.append(f"        '{m}' => {d:.4f}, // {', '.join(names[x] for x in l)}")
    lines += ['    ];', '',
              '    /** The drift for a business model, walking up its parents to the nearest one measured. */',
              '    public static function driftFor(object $model): float', '    {',
              '        for ($class = $model::class; $class !== false; $class = get_parent_class($class)) {',
              "            $short = substr($class, (int) strrpos($class, '\\\\') + 1);",
              '            if (isset(self::DRIFT_BY_MODEL[$short])) {', '                return self::DRIFT_BY_MODEL[$short];', '            }', '        }', '',
              '        return self::ALL_INDUSTRIES_DRIFT;', '    }', '}', '']
    open(out, 'w').write('\n'.join(lines))
    print('wrote', out)
